#!/usr/bin/env python3
"""
Build-time budget gate for the x86 core (logic; CLI is scripts/budget_gate.py).

Why this exists
---------------
Two classes of failure got through a night of parallel lanes, and no test
catches either one.

1. SILENT BUDGET EXHAUSTION. ITCM went from 11.3 KB free to 5,840 B free in one
   night across four lanes, none of which could see the others' consumption.
   RAM_EMU overshoot is worse than silent: the guest RAM claim returns NULL,
   `core_ready` stays 0, the frame loop paints nothing, and it presents as an
   unrelated bug. That signature has taken out at least three instrumented
   builds in this project's history; `X86_VPROF=1` is one of them (STATUS.md,
   "What is broken right now").

2. DOCUMENTATION ROT. docs/07's per-opcode table was 249 commits stale and
   mis-tasked two agents. It is generated by scripts/gen_opcode_coverage.py,
   which has a --check mode -- but nothing ran it.

This is a GUARD, not a pipeline: one command, exits non-zero when something
regressed. Nothing here runs unless a human or an agent invokes it.

What it refuses to do
---------------------
REPORT NUMBERS FROM A STALE ELF. `make: Nothing to be done` produced stale
numbers once and they were briefly reported as real. So the gate re-links from
scratch by default -- it DELETES the ELF first, which no make shortcut can
satisfy -- and when it is handed an ELF instead (--no-build) it compares that
ELF's mtime against every tracked source and REFUSES rather than reporting a
number it cannot stand behind.

Note also that build flags are not dependencies in this tree (TOOLING.md,
Non-negotiables). The recorded thresholds are for a STOCK build; extra make
variables change the sizes, and the gate says so rather than pretending the
comparison is meaningful.

The numbers
-----------
`__CORE_ITCM_CODE_END__` is the end of the pinned hot code in the 64 KB ITCM.
`__CORE_BSS_END__` is where the core stops and `ram_malloc()`'s bump starts, so
everything above it up to `__RAM_EMU_END__` is what the guest can be given.

The pager hands out frames of stride X86_PG_STRIDE = 4,104, not 4,096: every
frame carries 8 bytes of granule-seam slack (x86_pager.h, docs/10). A full
640 KB real-mode address space is 160 frames = 656,640 B. The frame count this
gate derives from `__CORE_BSS_END__` alone is an UPPER BOUND -- other RAM_EMU
claims land before the guest pool, so the live `guest_ram_pages` is lower --
which makes it a sound necessary condition and nothing more. Treat a DROP in it
as a regression; do not quote it as the pool size. The pool size is measured at
tier 2 by reading `guest_ram_pages` / `guest_ram_pages_short`.
"""

import json
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

DEFAULT_ELF = "build/core/dos_core.elf"
DEFAULT_THRESHOLDS = "tests/budgets.json"

NM = os.environ.get("NM", "arm-none-eabi-nm")

ITCM_BYTES = 65536
PG_STRIDE = 4104          # X86_PG_SIZE + X86_PG_SLACK, x86_pager.h
PG_FULL_FRAMES = 160      # the whole 640 KB real-mode address space

# Extensions whose edit invalidates a linked ELF: anything that reaches the
# core's text, data or bss, plus the build description itself.
SRC_SUFFIXES = (".c", ".h", ".S", ".s", ".inc", ".ld")
SRC_NAMES = ("Makefile", "Makefile.core")


def _run(cmd, **kw):
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, **kw)


def read_symbols(elf):
    """{name: address} for every symbol nm reports, absolute symbols included."""
    proc = _run([NM, elf])
    if proc.returncode != 0:
        raise RuntimeError("%s failed on %s: %s" % (NM, elf, proc.stderr.strip()))
    syms = {}
    for line in proc.stdout.splitlines():
        parts = line.split()
        if len(parts) == 3:
            syms[parts[2]] = int(parts[0], 16)
    return syms


def tracked_sources():
    """Tracked files whose modification invalidates a link, absolute paths."""
    proc = _run(["git", "ls-files"])
    if proc.returncode != 0:
        return []
    out = []
    for rel in proc.stdout.splitlines():
        base = os.path.basename(rel)
        if rel.endswith(SRC_SUFFIXES) or base in SRC_NAMES:
            out.append(os.path.join(ROOT, rel))
    return out


def newer_than_elf(elf):
    """Tracked sources modified after `elf` was linked. Empty == ELF is fresh."""
    try:
        elf_mtime = os.path.getmtime(elf)
    except OSError:
        return None
    stale = []
    for path in tracked_sources():
        try:
            if os.path.getmtime(path) > elf_mtime:
                stale.append(os.path.relpath(path, ROOT))
        except OSError:
            pass
    return sorted(stale)


def force_build(elf, make_args=(), clean=False, verbose=False):
    """Re-link, unconditionally.

    Deleting the ELF is the point: `make: Nothing to be done` cannot satisfy a
    missing target, so the link genuinely re-runs and the symbols genuinely
    come from this tree. --clean additionally drops the objects, which is what
    a build-FLAG change needs, flags not being dependencies here.
    """
    if clean:
        for d in (os.path.join(ROOT, "build", "core"),
                  os.path.join(ROOT, "lib", "FatFs")):
            if os.path.isdir(d):
                for f in os.listdir(d):
                    if f.endswith(".o"):
                        os.remove(os.path.join(d, f))
    abs_elf = os.path.join(ROOT, elf)
    if os.path.exists(abs_elf):
        os.remove(abs_elf)
    cmd = ["make", "-f", "Makefile.core", "-j8"] + list(make_args)
    proc = _run(cmd)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout[-4000:] + proc.stderr[-4000:])
        raise RuntimeError("build failed: " + " ".join(cmd))
    if not os.path.exists(abs_elf):
        raise RuntimeError(
            "build reported success but %s does not exist -- the gate deletes "
            "the ELF before building, so this means the make target does not "
            "produce it" % elf)
    if verbose:
        sys.stdout.write(proc.stdout[-2000:])
    return abs_elf


def load_thresholds(path):
    with open(os.path.join(ROOT, path)) as fh:
        return json.load(fh)


def measure(elf):
    """Derive every number the gate reports from one ELF."""
    syms = read_symbols(elf)
    missing = [s for s in ("__CORE_ITCM_CODE_END__", "__CORE_BSS_END__",
                           "__RAM_EMU_END__") if s not in syms]
    if missing:
        raise RuntimeError("symbols missing from %s: %s"
                           % (elf, ", ".join(missing)))
    itcm_end = syms["__CORE_ITCM_CODE_END__"]
    bss_end = syms["__CORE_BSS_END__"]
    ram_end = syms["__RAM_EMU_END__"]
    headroom = ram_end - bss_end
    return {
        "itcm_code_end": itcm_end,
        "itcm_free": ITCM_BYTES - itcm_end,
        "core_bss_end": bss_end,
        "ram_emu_end": ram_end,
        "ram_emu_headroom": headroom,
        # UPPER BOUND -- see the module docstring.
        "frames_implied": max(0, headroom // PG_STRIDE),
        "frames_wanted_bytes": PG_FULL_FRAMES * PG_STRIDE,
    }


def check(m, thr):
    """Compare measurements to thresholds. Returns (failures, notes)."""
    fails, notes = [], []

    lim = thr["itcm_code_end_max"]
    if m["itcm_code_end"] > lim:
        fails.append(
            "ITCM REGRESSED: __CORE_ITCM_CODE_END__ = 0x%X, budget 0x%X "
            "(+%d B over). ITCM free is %d B of %d."
            % (m["itcm_code_end"], lim, m["itcm_code_end"] - lim,
               m["itcm_free"], ITCM_BYTES))
    elif m["itcm_code_end"] < lim:
        notes.append(
            "ITCM shrank by %d B (0x%X vs budget 0x%X) -- lower the budget in "
            "%s to lock the win in."
            % (lim - m["itcm_code_end"], m["itcm_code_end"], lim,
               DEFAULT_THRESHOLDS))

    lim = thr["core_bss_end_max"]
    if m["core_bss_end"] > lim:
        fails.append(
            "RAM_EMU REGRESSED: __CORE_BSS_END__ = 0x%X, budget 0x%X (+%d B "
            "over). That is %d pager frame(s) taken from the guest. "
            "Overshooting RAM_EMU is SILENT: guest_ram returns NULL, "
            "core_ready stays 0, and the frame loop paints nothing."
            % (m["core_bss_end"], lim, m["core_bss_end"] - lim,
               (m["core_bss_end"] - lim + PG_STRIDE - 1) // PG_STRIDE))
    elif m["core_bss_end"] < lim:
        notes.append(
            "RAM_EMU shrank by %d B (0x%X vs budget 0x%X) -- lower the budget "
            "in %s to lock the win in."
            % (lim - m["core_bss_end"], m["core_bss_end"], lim,
               DEFAULT_THRESHOLDS))

    lim = thr["frames_implied_min"]
    if m["frames_implied"] < lim:
        fails.append(
            "PAGER FRAMES REGRESSED: __CORE_BSS_END__ implies at most %d "
            "frames of stride %d, recorded floor %d (-%d)."
            % (m["frames_implied"], PG_STRIDE, lim,
               lim - m["frames_implied"]))

    if m["ram_emu_headroom"] < m["frames_wanted_bytes"]:
        notes.append(
            "The full %d-frame pool wants %d B and only %d B is free above "
            "__CORE_BSS_END__, so the pool CANNOT reach 160 frames on this "
            "tree and the NOR snapshot's guest_ram_pages==160 guard refuses. "
            "PRE-EXISTING; measure guest_ram_pages at tier 2 for the real "
            "count." % (PG_FULL_FRAMES, m["frames_wanted_bytes"],
                        m["ram_emu_headroom"]))

    return fails, notes


def run_opcode_check():
    """gen_opcode_coverage.py --check: has docs/07 rotted again?"""
    proc = _run([sys.executable, "scripts/gen_opcode_coverage.py", "--check"])
    return proc.returncode, (proc.stdout + proc.stderr).strip()


def run_asm_advisory():
    """asm_metrics against tests/asm_baseline.json -- ADVISORY, never fatal.

    See TOOLING.md: the baseline is a review aid for per-handler instruction
    growth, not a budget. It drifts with every legitimate merge, and a lane
    refreshing it inside its own change would fold pre-existing drift under its
    own diff. It is refreshed as a standalone commit; this arm only reports.
    """
    if not os.path.exists(os.path.join(ROOT, "test_core.elf")):
        return None, ("test_core.elf not built (`make test_core.elf`) -- "
                      "advisory arm skipped")
    proc = _run([sys.executable, "scripts/asm_metrics.py"])
    return proc.returncode, (proc.stdout + proc.stderr).strip()
